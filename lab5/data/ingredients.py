@dataclass(frozen=True)
class Ingredient:
    id: str
    name: str
    category: str
    rarity: int


def _build() -> dict:
    try:
        result = {}
        for cat_id in CATEGORIES:
            names = _NAMES[cat_id]
            if len(names) != len(_RARITY_BY_INDEX):
                raise DataError(f"Категорія {cat_id}: має бути {len(_RARITY_BY_INDEX)} назв, є {len(names)}")
            for i, name in enumerate(names):
                ing_id = f"{cat_id}_{i:02d}"
                result[ing_id] = Ingredient(ing_id, name, cat_id, _RARITY_BY_INDEX[i])
        if len(result) < 200:
            raise DataError(f"Інгредієнтів {len(result)}, потрібно мінімум 200")
        if len({ing.name for ing in result.values()}) != len(result):
            raise DataError("Назви інгредієнтів повторюються")
        return result
    except KeyError as e:
        raise DataError(f"Немає списку назв для категорії {e}") from e


INGREDIENTS = _build()


def get_ingredient(ing_id: str) -> Ingredient:
    try:
        return INGREDIENTS[ing_id]
    except KeyError as e:
        raise DataError(f"Невідомий інгредієнт: {ing_id}") from e
